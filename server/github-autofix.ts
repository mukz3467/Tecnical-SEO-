import { randomUUID } from 'node:crypto';

type GithubFile = { sha?: string; content?: string };

function configured() {
  const token = process.env.AUTOFIX_GITHUB_TOKEN;
  const repository = process.env.AUTOFIX_GITHUB_REPOSITORY;
  const allowedHosts = (process.env.AUTOFIX_ALLOWED_HOSTS || '')
    .split(',')
    .map(host => host.trim().toLowerCase())
    .filter(Boolean);
  return { token, repository, allowedHosts };
}

async function githubRequest<T>(url: string, token: string, init: RequestInit = {}): Promise<T> {
  const response = await fetch(url, {
    ...init,
    headers: {
      Accept: 'application/vnd.github+json',
      Authorization: `Bearer ${token}`,
      'X-GitHub-Api-Version': '2022-11-28',
      ...(init.body ? { 'Content-Type': 'application/json' } : {}),
      ...init.headers
    }
  });
  if (!response.ok) {
    const detail = await response.text().catch(() => '');
    throw new Error(`GitHub API ${response.status}: ${detail.slice(0, 500)}`);
  }
  return response.json() as Promise<T>;
}

/**
 * Creates a reviewable PR containing only generated robots.txt and sitemap.xml.
 * It never writes directly to the production/default branch.
 */
export async function createSafeAutoFixPullRequest(input: {
  targetDomain: string;
  sitemapXml: string;
  robotsTxt: string;
}): Promise<{ status: 'created' | 'skipped'; url?: string; reason?: string }> {
  const { token, repository, allowedHosts } = configured();
  if (!token || !repository) {
    return { status: 'skipped', reason: 'GitHub auto-fix is not configured; suggestions remain downloadable.' };
  }
  const host = input.targetDomain.toLowerCase();
  if (!allowedHosts.includes(host)) {
    return { status: 'skipped', reason: `Host ${host} is not in AUTOFIX_ALLOWED_HOSTS; no repository files were changed.` };
  }
  if (!/^[A-Za-z0-9_.-]+\/[A-Za-z0-9_.-]+$/.test(repository)) {
    throw new Error('AUTOFIX_GITHUB_REPOSITORY must use owner/repository format.');
  }

  const api = 'https://api.github.com';
  const headers = { };
  const repo = await githubRequest<{ default_branch: string }>(`${api}/repos/${repository}`, token);
  const base = repo.default_branch || 'main';
  const branch = `autoindex/seo-fix-${new Date().toISOString().replace(/[^0-9]/g, '').slice(0, 14)}-${randomUUID().slice(0, 6)}`;
  const baseRef = await githubRequest<{ object: { sha: string } }>(`${api}/repos/${repository}/git/ref/heads/${encodeURIComponent(base)}`, token);
  await githubRequest(`${api}/repos/${repository}/git/refs`, token, {
    method: 'POST',
    body: JSON.stringify({ ref: `refs/heads/${branch}`, sha: baseRef.object.sha })
  });

  const files = [
    { path: 'robots.txt', content: input.robotsTxt },
    { path: 'sitemap.xml', content: input.sitemapXml }
  ];
  for (const file of files) {
    let existing: GithubFile | undefined;
    try {
      existing = await githubRequest<GithubFile>(`${api}/repos/${repository}/contents/${file.path}?ref=${encodeURIComponent(branch)}`, token);
    } catch (error) {
      if (!(error instanceof Error) || !error.message.startsWith('GitHub API 404:')) throw error;
    }
    await githubRequest(`${api}/repos/${repository}/contents/${file.path}`, token, {
      method: 'PUT',
      body: JSON.stringify({
        message: `AutoIndex AI: prepare SEO ${file.path}`,
        content: Buffer.from(file.content, 'utf8').toString('base64'),
        branch,
        ...(existing?.sha ? { sha: existing.sha } : {})
      })
    });
  }

  const pr = await githubRequest<{ html_url: string }>(`${api}/repos/${repository}/pulls`, token, {
    method: 'POST',
    body: JSON.stringify({
      title: `AutoIndex AI: safe technical SEO fixes for ${host}`,
      head: branch,
      base,
      body: [
        '## Auto-generated technical SEO patch',
        '',
        `Target host: ${host}`,
        '',
        'This PR updates only `robots.txt` and `sitemap.xml` from the completed crawl. It does not alter HTML, scripts, headers, or application code.',
        'Review the sitemap URLs and crawl rules before merging. Production files are not changed until this PR is merged and the hosting platform deploys it.',
        '',
        'Generated by AutoIndex AI.'
      ].join('\n')
    })
  });
  return { status: 'created', url: pr.html_url };
}
